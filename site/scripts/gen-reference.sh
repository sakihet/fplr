#!/usr/bin/env bash
# Generate the command reference pages under src/content/docs/reference/
# by running fplr against the live FPL API.
#
# Usage: site/scripts/gen-reference.sh  (run from the repo root, after cargo build --release)
set -euo pipefail

FPLR="${FPLR:-$PWD/target/release/fplr}"
OUT_DIR="$(cd "$(dirname "$0")/.." && pwd)/src/content/docs/reference"
MAX_LINES=30

# Run with an empty HOME so no manager ID from the user's config leaks into the output
TMP_HOME="$(mktemp -d)"
trap 'rm -rf "$TMP_HOME"' EXIT

fplr() {
	HOME="$TMP_HOME" TZ=Europe/London "$FPLR" --no-color "$@"
}

GW="$(fplr status | awk 'NR == 2 { print $1 }')"

# Print help without the global options shared by every command
help_text() {
	fplr "$@" --help |
		sed -n '/^Usage:/,$p' | sed 's/[[:space:]]*$//' |
		grep -vE -- '--no-cache|--no-color|-h, --help|-V, --version' |
		# Drop the "Options:" header left empty when only global options exist
		awk '{ lines[NR] = $0 } END { n = NR; while (n > 0 && (lines[n] == "" || lines[n] == "Options:")) n--; for (i = 1; i <= n; i++) print lines[i] }'
}

# Replace real manager IDs, team names and manager names in tables that list managers
mask_managers() {
	ruby -E UTF-8 -e '
		cols = nil
		n = 0
		$stdin.each_line do |line|
			if line.include?("Manager ID") && line.include?("Team Name")
				team = line.index("Team Name")
				mgr = line.index("Manager", team)
				cols = { id: line.index("Manager ID"), team: team, mgr: mgr, next: line.index(/\S/, mgr + "Manager".length) }
				n = 0
			elsif cols && line.strip.empty?
				cols = nil
			elsif cols && line.length > cols[:next]
				n += 1
				line[cols[:id]...cols[:team]] = line[cols[:id]...cols[:team]].gsub(/\d/, "x")
				line[cols[:team]...cols[:mgr]] = "Team #{n}".ljust(cols[:mgr] - cols[:team])
				line[cols[:mgr]...cols[:next]] = "Manager #{n}".ljust(cols[:next] - cols[:mgr])
			end
			print line
		end
	'
}

# Print a command section. $1 = command path, $2 = example args (empty for none)
section() {
	local cmd="$1" example="$2" desc output
	read -ra words <<<"$cmd"
	desc="$(fplr "${words[@]}" --help | head -n 1)"

	printf '## %s\n\n%s\n\n```text\n%s\n```\n\n' "$cmd" "$desc" "$(help_text "${words[@]}")"

	if [[ -n "$example" ]]; then
		read -ra args <<<"$example"
		output="$(fplr "${args[@]}" | sed 's/[[:space:]]*$//' | mask_managers)"
		printf '**Example**\n\n```sh\nfplr %s\n```\n\n```text\n%s\n```\n\n' \
			"$example" "$(head -n "$MAX_LINES" <<<"$output")"
	fi
}

# Write a page. $1 = file name, $2 = title, $3 = sidebar order, $4 = description,
# remaining args = "command|example" entries
page() {
	local file="$1" title="$2" order="$3" description="$4" entry
	shift 4
	{
		printf -- '---\ntitle: %s\ndescription: %s\nsidebar:\n  order: %s\n---\n\n' \
			"$title" "$description" "$order"
		printf '<!-- Generated by site/scripts/gen-reference.sh. Do not edit by hand. -->\n\n'
		if [[ "$*" == *"|"[!\ ]* ]]; then
			printf ':::note\nExample output was captured during Gameweek %s.\n:::\n\n' "$GW"
		fi
		for entry in "$@"; do
			section "${entry%%|*}" "${entry#*|}"
		done
	} >"$OUT_DIR/$file"
	echo "wrote $OUT_DIR/$file"
}

mkdir -p "$OUT_DIR"

